%===========================================
% 伝達関数 G(s) = (1/p)^n / (s + 1/p)^n のステップ応答
% n = 1, 2 の比較
%===========================================

clear; clc; close all;

%-------------------------------------------
% パラメータ設定
%-------------------------------------------
p = 2;                 % 定数 p の値
n_values = [1, 2];     % 比較する n の値

%-------------------------------------------
% 各 n に対して伝達関数を定義・応答を計算
%-------------------------------------------
s = tf('s');           % s を伝達関数変数として定義
colors = lines(length(n_values)); % グラフ色設定

figure;
hold on;

for i = 1:length(n_values)
    n = n_values(i);
    
    % 伝達関数 G(s) = (1/p)^n / (s + 1/p)^n
    G = (1/p)^n / (s + 1/p)^n;
    
    % ステップ応答データを取得
    [y, t] = step(G);
    
    % 応答をプロット
    plot(t, y, 'Color', colors(i,:), 'LineWidth', 1.5, ...
         'DisplayName', sprintf('n = %d', n));
end

%-------------------------------------------
% グラフ設定
%-------------------------------------------
grid on;
legend('show', 'Location', 'best');
title('ステップ応答比較: G(s) = (1/p)^n / (s + 1/p)^n');
xlabel('時間 [s]');
ylabel('出力');
